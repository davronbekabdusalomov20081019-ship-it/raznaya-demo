// Moscow time open status (salon is open every day 10:00–21:00)
window.openStatus = () => {
  const now = new Date(Date.now() + (new Date().getTimezoneOffset() + 180) * 60000);
  const h = now.getHours() + now.getMinutes() / 60;
  const open = h >= SALON.open && h < SALON.close;
  return { open, text: open ? `Открыто до ${SALON.close}:00` : `Откроемся в ${SALON.open}:00` };
};
